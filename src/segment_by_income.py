"""Do lower- and higher-income neighbourhoods respond differently to the private label price?

Splits stores at the median income of their trading area, refits the demand model in each
half and reruns the private label price sweep, to see whether a store-group test should
start in one kind of neighbourhood.

Usage: python src/segment_by_income.py   (writes results/income_segments.md)
"""
from __future__ import annotations

import pandas as pd

import demand_model as dm
import optimise_prices as op
from build_panel import BRANDS, PANEL_PATH

REPORT_PATH = dm.ROOT / "results" / "income_segments.md"
SWEEP_PRICES = [0.69, 0.75, 0.79, 0.85, 0.89, 0.94]


def split_by_income(panel: pd.DataFrame) -> dict[str, pd.DataFrame]:
    """Two groups of stores at the median store income; stores without demographics are dropped."""
    income = panel.dropna(subset=["log_income"]).groupby("store")["log_income"].first()
    high = income > income.median()
    return {
        "Lower-income stores": panel[panel["store"].isin(income.index[~high])],
        "Higher-income stores": panel[panel["store"].isin(income.index[high])],
    }


def main() -> None:
    lines = ["# Results by neighbourhood income (generated by `src/segment_by_income.py`)", "",
             "Stores split at the median income of their trading area (1990 census). Each half is modelled "
             "separately. Same assumptions as `pricing.md`.", ""]
    own_rows = ["| Group | Stores | " + " | ".join(f"{b} own elasticity" for b in BRANDS) + " |",
                "| --- | --- | " + " | ".join("---" for _ in BRANDS) + " |"]
    sweeps = []
    for name, group in split_by_income(pd.read_csv(PANEL_PATH)).items():
        fits = dm.fit_all(group)
        path = dm.ROOT / "results" / f"elasticities_{name.split('-')[0].lower()}_income.json"
        dm.save_results(fits, group, path)
        results = dm.load_results(path)
        market = op.Market.from_results(results)
        own = " | ".join(f"{f.elasticities[f.brand]:.2f} (se {f.std_errors[f.brand]:.2f})" for f in fits)
        own_rows.append(f"| {name} | {group['store'].nunique()} | {own} |")
        sweeps.append(op.price_sweep(market, results, op.PRIVATE_LABEL, SWEEP_PRICES, draws=1000)
                      .replace("## Category profit", f"## {name}: category profit"))
        print(f"{name} done")
    REPORT_PATH.write_text("\n".join(lines + own_rows) + "\n" + "".join(sweeps), encoding="utf-8")
    print(REPORT_PATH.read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
